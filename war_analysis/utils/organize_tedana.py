"""Organize tedana multi-echo denoised functional MRI outputs into BIDS structure.

Locates multi-echo denoised BOLD files generated by tedana and moves them into
the appropriate session/func directories with standard BIDS naming conventions.
"""

import argparse
import os
import re
import shutil
import sys
from typing import List, Optional, Tuple


def organize_tedana_file(
    tedana_file_path: str,
    root_dir: str,
) -> Optional[Tuple[str, str]]:
    """Organize an individual tedana denoised BOLD file into BIDS session structure.

    Args:
        tedana_file_path: Path to the denoised BOLD NIfTI file inside tedana output directory.
        root_dir: Parent directory of the subject/session.

    Returns:
        Tuple of (source_path, target_path) if moved/copied, or None if skipped.
    """
    filename = os.path.basename(tedana_file_path)
    pattern = r"(sub-[^_]+)_(ses-[^_]+)_task-war_run-([^_]+)_space-MNI152NLin2009cAsym_desc-denoised_bold(\.nii(\.gz)?)"
    match = re.match(pattern, filename)
    if not match:
        return None

    sub_x = match.group(1)
    ses_y = match.group(2)
    run_z = match.group(3)

    sibling_ses_path = os.path.join(root_dir, ses_y)
    if not os.path.exists(sibling_ses_path):
        print(f"Warning: Sibling folder {sibling_ses_path} not found for {filename}", file=sys.stderr)
        return None

    target_filename = (
        f"{sub_x}_{ses_y}_task-war_run-{run_z}_space-MNI152NLin2009cAsym_desc-preproc_bold.nii.gz"
    )

    possible_dirs = [
        os.path.join(sibling_ses_path, "func"),
        sibling_ses_path,
    ]

    target_path = None
    found_target = False
    for d in possible_dirs:
        possible_path = os.path.join(d, target_filename)
        if os.path.exists(possible_path):
            target_path = possible_path
            found_target = True
            break

    if not found_target:
        func_dir = os.path.join(sibling_ses_path, "func")
        if os.path.exists(func_dir):
            target_path = os.path.join(func_dir, target_filename)
        else:
            target_path = os.path.join(sibling_ses_path, target_filename)

    if found_target and target_path is not None:
        backup_filename = target_filename.replace(".nii.gz", "_old.nii.gz")
        backup_path = os.path.join(os.path.dirname(target_path), backup_filename)
        if not os.path.exists(backup_path):
            print(f"Renaming existing file {target_path} to backup {backup_path}")
            os.rename(target_path, backup_path)
        else:
            print(f"Backup file {backup_path} already exists. Skipping backup rename.")

    print(f"Copying {tedana_file_path} to {target_path}")
    shutil.copy2(tedana_file_path, target_path)
    return (tedana_file_path, target_path)


def process_directory(root_dir: str) -> List[Tuple[str, str]]:
    """Scan directory recursively for tedana output folders and organize denoised files.

    Args:
        root_dir: Base directory to scan.

    Returns:
        List of tuples containing (source_file, target_file) for organized files.
    """
    print(f"Scanning directory: {root_dir}")
    organized: List[Tuple[str, str]] = []

    for dirpath, dirs, _ in os.walk(root_dir):
        if "tedana" in dirs:
            tedana_path = os.path.join(dirpath, "tedana")
            for file in os.listdir(tedana_path):
                source_file_path = os.path.join(tedana_path, file)
                if os.path.isfile(source_file_path):
                    res = organize_tedana_file(source_file_path, dirpath)
                    if res:
                        organized.append(res)

    print(f"Organized {len(organized)} tedana file(s).")
    return organized


def parse_args(argv: Optional[List[str]] = None) -> argparse.Namespace:
    """Parse CLI arguments for organize_tedana."""
    parser = argparse.ArgumentParser(
        description="Organize tedana denoised outputs into standard BIDS structure."
    )
    parser.add_argument(
        "root_dir",
        nargs="?",
        default=os.getcwd(),
        help="Root directory to scan for tedana output folders (default: current working directory).",
    )
    return parser.parse_args(argv)


def main(argv: Optional[List[str]] = None) -> int:
    """CLI entry point for organize_tedana."""
    args = parse_args(argv)
    if not os.path.isdir(args.root_dir):
        print(f"Root directory does not exist: {args.root_dir}", file=sys.stderr)
        return 1

    process_directory(args.root_dir)
    return 0


if __name__ == "__main__":
    sys.exit(main())
